#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const EXPECTED_SHA256 = '1d8a944f88d7952f7ef7c5167fef3c67995bcae24543949710231b03a201acda';
const SOURCE_URL = 'https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt';
const CATEGORY_DETAILS = {
    'Smileys & Emotion': ['smileys-emotion', 'Smileys & emotion', '😀'],
    'People & Body': ['people-body', 'People & body', '👋'],
    'Animals & Nature': ['animals-nature', 'Animals & nature', '🐻'],
    'Food & Drink': ['food-drink', 'Food & drink', '🍎'],
    'Travel & Places': ['travel-places', 'Travel & places', '🚗'],
    Activities: ['activities', 'Activities', '⚽'],
    Objects: ['objects', 'Objects', '💡'],
    Symbols: ['symbols', 'Symbols', '❤'],
    Flags: ['flags', 'Flags', '🏁'],
};

const [inputPath, outputPath] = process.argv.slice(2);
if (!inputPath || !outputPath) {
    console.error('Usage: node scripts/generate-emoji-catalog.mjs <emoji-test.txt> <output.ts>');
    process.exit(1);
}

const source = await readFile(inputPath);
const digest = createHash('sha256').update(source).digest('hex');
if (digest !== EXPECTED_SHA256) {
    throw new Error(`Unexpected emoji-test.txt SHA-256: ${digest}`);
}

let activeCategory;
const entries = [];
for (const line of source.toString('utf8').split('\n')) {
    const group = line.match(/^# group: (.+)$/)?.[1];
    if (group) {
        activeCategory = CATEGORY_DETAILS[group]?.[0];
        continue;
    }
    const match = line.match(/^([0-9A-F ]+)\s*; fully-qualified\s*#\s+\S+\s+E\d+\.\d+\s+(.+)$/);
    if (!match) continue;
    if (!activeCategory) throw new Error(`Fully-qualified entry has no supported group: ${line}`);
    const emoji = match[1].trim().split(/\s+/).map(value => String.fromCodePoint(Number.parseInt(value, 16))).join('');
    entries.push([emoji, match[2], activeCategory]);
}

const categories = Object.values(CATEGORY_DETAILS).map(([id, label, icon]) => ({
    id,
    label,
    icon,
    count: entries.filter(entry => entry[2] === id).length,
}));
const categoryIds = categories.map(category => JSON.stringify(category.id)).join(' | ');
const catalog = `/**
 * Generated by scripts/generate-emoji-catalog.mjs from Unicode Emoji 17.0.
 * Immutable source: ${SOURCE_URL}
 * SHA-256: ${EXPECTED_SHA256}
 * Contains every fully-qualified entry except Emoji_Component records.
 * Copyright © 1991-2026 Unicode, Inc. Distributed under the Unicode License v3;
 * see ../../docs/unicode-license.md.
 */

export type EmojiCategoryId = ${categoryIds};

export type EmojiCatalogEntry = readonly [emoji: string, name: string, category: EmojiCategoryId];

export const EMOJI_CATEGORIES = ${JSON.stringify(categories, null, 4)} as const;

export const EMOJI_CATALOG: readonly EmojiCatalogEntry[] = [
${entries.map(entry => `    ${JSON.stringify(entry)},`).join('\n')}
];
`;

await writeFile(outputPath, catalog);
